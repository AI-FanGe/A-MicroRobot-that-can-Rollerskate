"""Draw the 小小白 logo (the robot reduced to a few rounded shapes) for the web UI and the app.

Writes webui/img/logo.svg and the Android adaptive icon layers under
android/app/src/main/res (foreground, black background, monochrome for themed icons).
Run from the repo root after changing the shapes (`make app-icon`):

    python3 scripts/build_app_icon.py
"""

from __future__ import annotations

import math
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RES = REPO / "android" / "app" / "src" / "main" / "res"

WHITE = "#FFFFFF"
SCREEN = "#10141C"
EYE = "#FFE8C8"
LED = "#2DD4BF"

# On a 100×100 canvas, the robot's body spans y 11–86; DY centres it.
DY = 1.5


def _num(v: float) -> str:
    text = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


def rrect(x0: float, y0: float, x1: float, y1: float, r: float) -> str:
    y0, y1 = y0 + DY, y1 + DY
    w, h = x1 - x0, y1 - y0
    r = min(r, w / 2, h / 2)
    f = _num
    return (f"M{f(x0 + r)},{f(y0)}h{f(w - 2 * r)}a{f(r)},{f(r)} 0 0 1 {f(r)},{f(r)}v{f(h - 2 * r)}"
            f"a{f(r)},{f(r)} 0 0 1 {f(-r)},{f(r)}h{f(-(w - 2 * r))}a{f(r)},{f(r)} 0 0 1 {f(-r)},{f(-r)}"
            f"v{f(-(h - 2 * r))}a{f(r)},{f(r)} 0 0 1 {f(r)},{f(-r)}z")


def rpoly(points: list[tuple[float, float]], r: float) -> str:
    """A polygon with each corner rounded by a quadratic curve through the vertex."""
    pts = [(x, y + DY) for x, y in points]
    n = len(pts)
    out = []
    for i, (x, y) in enumerate(pts):
        px, py = pts[i - 1]
        nx, ny = pts[(i + 1) % n]
        a = _toward((x, y), (px, py), r)
        b = _toward((x, y), (nx, ny), r)
        out.append(f"{'M' if i == 0 else 'L'}{a[0]:.2f},{a[1]:.2f}Q{x:.2f},{y:.2f} {b[0]:.2f},{b[1]:.2f}")
    return "".join(out) + "z"


def _toward(p: tuple[float, float], q: tuple[float, float], d: float) -> tuple[float, float]:
    length = math.dist(p, q)
    t = min(d, length / 2) / length
    return p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t


HEAD = rrect(37, 11, 63, 32, 7)
SCREEN_P = rrect(43.5, 16.5, 56.5, 26, 2.5)
EYES = rrect(46, 19, 48, 23.5, 1) + rrect(52, 19, 54, 23.5, 1)
TORSO = rpoly([(36, 33.5), (64, 33.5), (62, 59.5), (38, 59.5)], 5)
CHEST = rrect(47, 38.2, 53, 39.8, 0.8)
LIMBS = rrect(27, 35, 35, 66, 4) + rrect(65, 35, 73, 66, 4) + rrect(37.5, 61, 48, 86, 3) + rrect(52, 61, 62.5, 86, 3)
BODY = HEAD + TORSO + LIMBS

LAYERS = [(BODY, WHITE), (SCREEN_P, SCREEN), (EYES, EYE), (CHEST, LED)]


def svg() -> str:
    paths = "\n".join(f'  <path fill="{color}" d="{d}"/>' for d, color in LAYERS)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
  <rect x="2" y="2" width="96" height="96" rx="24" fill="#000000"/>
{paths}
</svg>
"""


def vector(paths: list[tuple[str, str, str]]) -> str:
    """Adaptive icon layer: 108×108 viewport, robot scaled into the 66 dp safe circle."""
    s = 0.74
    tx, ty = 54 - 50 * s, 54 - (48.5 + DY) * s
    body = "\n".join(
        f'        <path android:fillColor="{color}"{fill} android:pathData="{d}"/>' for d, color, fill in paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/build_app_icon.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:scaleX="{s}" android:scaleY="{s}" android:translateX="{tx:.2f}" android:translateY="{ty:.2f}">
{body}
    </group>
</vector>
"""


BACKGROUND = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/build_app_icon.py -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="#FF000000"/>
</shape>
"""

ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/build_app_icon.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
"""


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print("wrote", path.relative_to(REPO))


def main() -> None:
    write(REPO / "webui" / "img" / "logo.svg", svg())
    write(RES / "drawable" / "ic_launcher_foreground.xml", vector([(d, c, "") for d, c in LAYERS]))
    # Themed icons only keep alpha: the body with the screen and chest light cut out, eyes inside the hole.
    even = ' android:fillType="evenOdd"'
    write(RES / "drawable" / "ic_launcher_monochrome.xml",
          vector([(BODY + SCREEN_P + CHEST, WHITE, even), (EYES, WHITE, "")]))
    write(RES / "drawable" / "ic_launcher_background.xml", BACKGROUND)
    for name in ("ic_launcher", "ic_launcher_round"):
        write(RES / "mipmap-anydpi-v26" / f"{name}.xml", ADAPTIVE)


if __name__ == "__main__":
    main()
